  const $ = (id) => document.getElementById(id);
  const reduce = window.matchMedia("(prefers-reduced-motion: reduce)").matches;

  /* Langue */
  function paintLang() {
    document.querySelectorAll(".s-lang button").forEach((b) => b.setAttribute("aria-pressed", b.dataset.l === FSI18N.lang));
    document.title = "Field Shift — " + FSI18N.t("s.hero.title");
  }
  document.querySelector(".s-lang").addEventListener("click", (e) => {
    const b = e.target.closest("button[data-l]"); if (b) FSI18N.setLang(b.dataset.l);
  });
  document.addEventListener("fs:langchange", paintLang);

  /* Apparitions + compteurs */
  const io = new IntersectionObserver((entries) => {
    entries.forEach((en) => {
      if (!en.isIntersecting) return;
      en.target.classList.add("is-in");
      en.target.querySelectorAll(".count").forEach(countUp);
      io.unobserve(en.target);
    });
  }, { threshold: 0.15 });
  document.querySelectorAll(".reveal").forEach((el, i) => { el.style.transitionDelay = (i % 4) * 80 + "ms"; io.observe(el); });
  function countUp(el) {
    const to = +el.dataset.to, t0 = performance.now(), dur = reduce ? 0 : 1400;
    const tick = (t) => { const k = dur ? Math.min(1, (t - t0) / dur) : 1; el.textContent = Math.round(to * (1 - Math.pow(1 - k, 3))); if (k < 1) requestAnimationFrame(tick); };
    requestAnimationFrame(tick);
  }

  /* Rail des données NASA */
  const rail = $("data-rail");
  const cards = () => [...rail.children];
  function railStep(dir) { const w = cards()[0].getBoundingClientRect().width + 18; rail.scrollBy({ left: dir * w, behavior: "smooth" }); }
  $("rail-prev").addEventListener("click", () => railStep(-1));
  $("rail-next").addEventListener("click", () => railStep(1));
  rail.addEventListener("scroll", () => {
    const w = cards()[0].getBoundingClientRect().width + 18;
    const i = Math.min(cards().length - 1, Math.round(rail.scrollLeft / w));
    $("rail-count").textContent = String(i + 1).padStart(2, "0") + "/" + String(cards().length).padStart(2, "0");
  }, { passive: true });

  /* Cartes satellite réelles (vue aérienne qui dérive lentement) */
  function satMap(el, center, zoom, opts) {
    if (!window.maplibregl || !Terra.hasWebGL()) return null;
    const style = Terra.satStyle(false);
    style.projection = { type: "mercator" };
    delete style.sky;
    const map = new maplibregl.Map(Object.assign({ container: el, style, center, zoom, interactive: false, attributionControl: false, fadeDuration: 0 }, opts || {}));
    return map;
  }
  function drift(map, path, ms) {
    if (!map || reduce) return;
    let i = 0;
    const go = () => { i = (i + 1) % path.length; map.easeTo({ center: path[i], duration: ms, easing: (t) => t, bearing: map.getBearing() + 4 }); };
    map.on("moveend", go);
    map.once("load", go);
  }
  // Hero : plaines agricoles du sud du Honduras (Choluteca), vue aérienne inclinée.
  const hero = satMap($("hero-map"), [-87.255, 13.215], 14.2, { pitch: 38, bearing: -20 });
  drift(hero, [[-87.255, 13.215], [-87.215, 13.235], [-87.19, 13.205], [-87.235, 13.19]], 26000);
  // Section terrain : champs du Burkina Faso, plus près.
  const fm = satMap($("field-map"), [-2.43, 13.62], 15.2, { pitch: 0 });
  drift(fm, [[-2.43, 13.62], [-2.41, 13.63], [-2.4, 13.61]], 30000);

  paintLang();
